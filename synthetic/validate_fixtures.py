"""Check the hand-written text corpora: every file still parses, and every account number, IFSC, UPI ID and phone
number in them is synthetic by the rules below. It reports what breaks a rule; it never edits a fixture.

The corpora (scenarios, variants, the labelled evaluation set, the mock bank records) were written with Claude, not
generated by code; synthetic/README.md says so and sets out the rules. The rules code can check:

  IFSC         must carry the DEMO prefix (DEMO0......), which no bank holds.
  number       an account or phone number (9 to 18 digits, written solid or in groups of 2 to 6 digits) must be
               visibly invented: a run of at least 4 consecutive digits up or down (1234, 98765) or at least
               2 doubled digits (0011, 5566).
  UPI ID       a word handle (rbi.invest@okaxis) is accepted; a numeric handle must pass the number rule.

These rules catch a number that does not look invented. They cannot prove that a number belongs to no one: a real
number can contain 2 doubled digits by chance, and a number spelled digit by digit (3 0 0 1 ...) is not read.
Names are not checked by code. web_registry.json is skipped: it holds real public registry answers recorded over
RDAP, not invented data, and says so in its own _note.

  python synthetic/validate_fixtures.py            # exit 0 when nothing breaks a rule, 1 otherwise
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "prototype" / "data"
CORPORA = [*sorted((DATA / "fixtures").glob("*.json")), *sorted((DATA / "eval").glob("*.json")),
           *sorted(p for p in (DATA / "mocks").iterdir() if p.name != "web_registry.json"),
           *sorted((ROOT / "datasets").rglob("*.json")), *sorted((ROOT / "datasets" / "mocks").glob("*.md"))]
IFSC = re.compile(r"\b[A-Z]{4}0[A-Z0-9]{6}\b")
UPI = re.compile(r"(?<![\w.@-])([\w.-]{2,})@([A-Za-z][A-Za-z0-9]+)\b(?!\.)")    # the (?!\.) skips e-mail
# 9 to 18 digits, written solid (30011223344556) or in groups (+91 98765 00011, 1600 123 4567)
NUMBER = re.compile(r"(?<![\w.,:-])\+?\d{2,18}(?:[ -]\d{2,6}){0,4}(?![\w:-]|[.,]\d)")


def run_length(digits: str) -> int:
    """Longest run of consecutive digits going up or down by one (1234 -> 4)."""
    best = 1
    for step in (1, -1):
        cur = 1
        for a, b in zip(digits, digits[1:]):
            cur = cur + 1 if int(b) - int(a) == step else 1
            best = max(best, cur)
    return best


def doubled(digits: str) -> int:
    """Non-overlapping doubled digits (0011 -> 2)."""
    n = i = 0
    while i < len(digits) - 1:
        if digits[i] == digits[i + 1]:
            n, i = n + 1, i + 2
        else:
            i += 1
    return n


def invented_number(number: str) -> bool:
    digits = number.lstrip("+")
    return run_length(digits) >= 4 or doubled(digits) >= 2


def synthetic_ifsc(code: str) -> bool:
    return code.startswith("DEMO0")


def findings(text: str) -> list[tuple[str, str]]:
    """(kind, value) for every identifier in `text` that breaks a rule, each value once."""
    out: dict[tuple[str, str], None] = {}
    for code in IFSC.findall(text):
        if not synthetic_ifsc(code):
            out[("IFSC", code)] = None
    for user, handle in UPI.findall(text):
        if user.isdigit() and not invented_number(user):
            out[("UPI ID", f"{user}@{handle}")] = None
    for number in NUMBER.findall(text):
        digits = re.sub(r"[ +-]", "", number)
        if 9 <= len(digits) <= 18 and not invented_number(digits):
            out[("number", number)] = None
    return list(out)


def parse(path: Path) -> str:
    """The file's text, after checking that a .json or .yaml file parses. Raises on a broken file."""
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".json":
        json.loads(text)
    elif path.suffix in (".yaml", ".yml"):
        import yaml
        yaml.safe_load(text)
    return text


def validate(paths: list[Path] = CORPORA) -> tuple[list[str], list[tuple[str, str, str]]]:
    """(files that do not parse, [(file, kind, value) that breaks a rule])."""
    broken, bad = [], []
    for p in paths:
        try:
            text = parse(p)
        except Exception as e:  # noqa: BLE001 - report every broken file, not just the first
            broken.append(f"{p.relative_to(ROOT)}: {e}")
            continue
        bad += [(str(p.relative_to(ROOT)), kind, value) for kind, value in findings(text)]
    return broken, bad


def main() -> int:
    broken, bad = validate()
    print(f"checked {len(CORPORA)} files")
    for line in broken:
        print(f"DOES NOT PARSE  {line}")
    for path, kind, value in bad:
        print(f"NOT SYNTHETIC BY THE RULES  {kind:7s} {value:22s} {path}")
    if not broken and not bad:
        print("every file parses; every IFSC, account number, UPI ID and phone number follows the rules")
    return 1 if broken or bad else 0


if __name__ == "__main__":
    sys.exit(main())
